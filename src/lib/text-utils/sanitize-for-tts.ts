// ── Markdown → 평문 정제 (TTS 안전망) ───────────────────────────────────────
//
// LLM에게 평문만 출력하도록 지시하지만(시스템 프롬프트), 모델이 어길 때를 대비해
// 음성 합성 직전 마크다운 문법을 제거한다. "별표 별표" 같은 발음 오류를 막는 게 목적.
//
// 클라이언트·서버 양쪽에서 쓸 수 있도록 의존성 없는 순수 함수로 둔다.

export function sanitizeForTTS(text: string): string {
  if (!text) return ''
  return text
    // 코드 블록 ```...``` → 제거 (인라인 코드 처리보다 먼저)
    .replace(/```[\s\S]*?```/g, '')
    // **굵게** → 굵게
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    // __굵게__ → 굵게
    .replace(/__([^_]+)__/g, '$1')
    // *기울임* → 기울임 (단순 곱셈 기호 `2 * 3`과 구분: 별표 뒤 첫 글자는 공백/별표 불가)
    .replace(/\*([^*\s][^*]*?)\*/g, '$1')
    // # 헤더 → (마커 제거)
    .replace(/^#{1,6}\s+/gm, '')
    // - / * / + 리스트 마커 → (제거)
    .replace(/^\s*[-*+]\s+/gm, '')
    // 1. 2. 순서 리스트 마커 → (제거)
    .replace(/^\s*\d+\.\s+/gm, '')
    // > 인용 마커 → (제거)
    .replace(/^\s*>\s?/gm, '')
    // `코드` → 코드
    .replace(/`([^`]+)`/g, '$1')
    // [텍스트](링크) → 텍스트
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    // ~~취소선~~ → 취소선
    .replace(/~~([^~]+)~~/g, '$1')
    // 표 구분 행 |---|---| → 제거
    .replace(/^\s*\|?[\s:|-]*-[\s:|-]*\|?\s*$/gm, '')
    // 표 셀 구분자 | → 공백
    .replace(/\s*\|\s*/g, ' ')
    // 줄바꿈 3개 이상 → 2개로 정리
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}
